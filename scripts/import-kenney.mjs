#!/usr/bin/env node
// Imports the Kenney City Kit GLBs used by Skyline into src/renderer/src/city/assets/.
//
//   node scripts/import-kenney.mjs <scratchpad>/models/kenney
//
// Steps: select curated files -> strip external texture refs -> remap UVs into one stacked
// colormap atlas -> measure (bounds, tris, origin) -> write models/<pack>/*.glb, textures/colormap.png
// and the generated manifest.ts. Re-running is idempotent (the source packs are never modified).
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { measureGlb, rewriteGlbForAtlas, classify } from './lib/glb.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ASSETS = path.join(ROOT, 'src/renderer/src/city/assets')
const KENNEY = process.argv[2]
if (!KENNEY) {
  console.error('usage: node scripts/import-kenney.mjs <dir containing kenney_city-kit-* packs>')
  process.exit(1)
}

// pack order = atlas slot order (see build-colormap.py)
const PACKS = [
  { name: 'commercial', dir: 'kenney_city-kit-commercial_2.1' },
  { name: 'roads', dir: 'kenney_city-kit-roads' },
  { name: 'suburban', dir: 'kenney_city-kit-suburban_20' }
]

const COMMERCIAL = [
  /^building-[a-n]\.glb$/, /^building-skyscraper-[a-e]\.glb$/,
  /^low-detail-building-([a-n]|wide-[ab])\.glb$/, /^detail-(awning|overhang|parasol)(-wide|-[ab])?\.glb$/
]
const ROADS = [
  /^road-(straight|bend|crossroad|intersection|end|crossing)\.glb$/, /^road-side(-[a-z]+)*\.glb$/,
  /^road-end-round\.glb$/, /^light-(square|curved)(-double)?\.glb$/, /^electricity-pole(-single|-wide)?\.glb$/,
  /^construction-(barrier|cone|fence|light)\.glb$/, /^dumpster\.glb$/, /^road-sign-[a-z-]+\.glb$/
]
const SUBURBAN = [/^building-type-[a-u]\.glb$/]
const SELECT = { commercial: COMMERCIAL, roads: ROADS, suburban: SUBURBAN }

// 1. colormap atlas
fs.mkdirSync(path.join(ASSETS, 'textures'), { recursive: true })
const colormapOut = path.join(ASSETS, 'textures/colormap.png')
execFileSync('python3', ['-I', path.join(ROOT, 'scripts/build-colormap.py'),
  ...PACKS.map((p) => path.join(KENNEY, p.dir, 'Models/GLB format/Textures/colormap.png')), colormapOut], { stdio: 'inherit' })

// 2. select, rewrite, measure
const models = []
PACKS.forEach((pack, slot) => {
  const srcDir = path.join(KENNEY, pack.dir, 'Models/GLB format')
  const outDir = path.join(ASSETS, 'models', pack.name)
  fs.rmSync(outDir, { recursive: true, force: true })
  fs.mkdirSync(outDir, { recursive: true })
  const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.glb') && SELECT[pack.name].some((re) => re.test(f))).sort()
  for (const file of files) {
    const id = file.replace(/\.glb$/, '')
    const raw = fs.readFileSync(path.join(srcDir, file))
    const rewritten = rewriteGlbForAtlas(raw, { slot, slots: PACKS.length })
    fs.writeFileSync(path.join(outDir, file), rewritten)
    const m = measureGlb(rewritten)
    const cls = classify(id, m.size.y, pack.name)
    models.push({ id, pack: pack.name, file: `models/${pack.name}/${file}`, cls, size: m.size, tris: m.tris, origin: m.origin })
  }
})

// 3. manifest.ts (generated; checked in). url = Vite ?url import so the asset is emitted next to the
// renderer bundle and resolved relative to index.html, which works from dev and from file:// builds.
const ident = (id) => id.replace(/[^a-zA-Z0-9]/g, '_')
const lines = []
lines.push('// GENERATED by scripts/import-kenney.mjs from the Kenney City Kit packs (CC0, https://kenney.nl).')
lines.push('// Do not edit by hand: re-run `node scripts/import-kenney.mjs <kenney dir>` instead.')
lines.push('')
for (const m of models) lines.push(`import ${ident(m.id)}_url from './${m.file}?url'`)
lines.push('')
lines.push('export type ModelClass = \'house\' | \'lowrise\' | \'midrise\' | \'tower\' | \'skyscraper\' | \'lowdetail\' | \'prop\' | \'road\'')
lines.push('export interface ModelDef {')
lines.push('  id: string')
lines.push('  cls: ModelClass')
lines.push('  /** Resolved asset URL (GLB). Works in dev and in the packaged file:// app. */')
lines.push('  url: string')
lines.push('  /** Native bounding box in model units (1 unit ~ one city cell). */')
lines.push('  size: { x: number; y: number; z: number }')
lines.push('  tris: number')
lines.push('}')
lines.push('')
lines.push('export const MODELS: ModelDef[] = [')
for (const m of models) {
  const s = m.size
  lines.push(`  { id: '${m.id}', cls: '${m.cls}', url: ${ident(m.id)}_url, size: { x: ${s.x}, y: ${s.y}, z: ${s.z} }, tris: ${m.tris} },`)
}
lines.push(']')
lines.push('')
lines.push('const BY_ID = new Map(MODELS.map((m) => [m.id, m]))')
lines.push('')
lines.push('/** Throws on an unknown id (typos fail loudly instead of rendering nothing). */')
lines.push('export function getModel(id: string): ModelDef {')
lines.push('  const def = BY_ID.get(id)')
lines.push('  if (!def) throw new Error(`unknown city model: ${id}`)')
lines.push('  return def')
lines.push('}')
lines.push('')
lines.push('export function modelsByClass(cls: ModelClass): ModelDef[] {')
lines.push('  return MODELS.filter((m) => m.cls === cls)')
lines.push('}')
lines.push('')
lines.push('/** Colormap atlas URL: commercial, roads and suburban palettes stacked vertically (512x1536). */')
lines.push(`export { default as COLORMAP_URL } from './textures/colormap.png?url'`)
lines.push('')
fs.writeFileSync(path.join(ASSETS, 'manifest.ts'), lines.join('\n'))

// 4. report
console.log(`imported ${models.length} models`)
for (const m of models) console.log(`${m.cls.padEnd(10)} ${m.id.padEnd(28)} ${m.size.x}x${m.size.y}x${m.size.z} tris=${m.tris} origin=(${m.origin.x},${m.origin.y},${m.origin.z})`)
